export function searchCountLabel(locale: Locale, shown: number, total: number) {
  return locale === 'zh'
    ? `找到 ${total} 条结果，已显示 ${shown} 条`
    : locale === 'de'
      ? `${total} Treffer · ${shown} angezeigt`
      : `${total} result${total === 1 ? '' : 's'} · ${shown} shown`;
}
